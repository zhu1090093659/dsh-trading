#!/usr/bin/env node
'use strict';

/**
 * Put back the files mygo v0.7.4 leaves out of an app's resources: every name
 * that starts with a dot (cmd/mygo/resources.go:551 hiddenName, applied at :643
 * while a resource directory is walked, so a dotted directory takes its contents
 * with it).
 *
 * The mac build restores them into the app bundle after `mygo build`
 * (restore-mygo-dotfiles.mjs) and signs again. A Windows installer is written
 * inside that same mygo build, so the same files have to arrive twice:
 *
 *   --macro <file>  writes the NSIS macro the installer includes: a File command
 *                   for every such file, into $INSTDIR plus the path the payload
 *                   is installed at, and a CreateDirectory for every such
 *                   directory. Generated on every build with the build machine's
 *                   absolute paths, so it is a build output, never committed.
 *   --app <dir>     copies them into an app directory (desktop/mygo/build/
 *                   windows-amd64, the app as installed) and checks every copy
 *                   byte for byte, so the app run straight out of build/ is whole
 *                   too. --check writes nothing and only verifies, which is what
 *                   the build runs against the installer's extracted payload.
 *
 * The list is never written by hand: it is what the staged payload holds. A
 * payload with no such entries produces an empty macro and a clean check.
 *
 * Usage:
 *   node scripts/stage-mygo-dotfiles.mjs --source <staged runtime> [options]
 *
 *   --source <dir>    the staged payload (desktop/mygo/resources/runtime)
 *   --prefix <path>   where the app installs it, inside $INSTDIR (runtime: mygo
 *                     ships resources/runtime as the folder beside the executable)
 *   --macro <file>    write the NSIS macro there
 *   --app <dir>       copy the entries into this app directory
 *   --check           with --app: verify only, write nothing
 *   --files-only      with --app: check files only, since an installer packs no
 *                     directory: a dotted directory that holds nothing is created
 *                     at install time by the macro, and unpacking an installer
 *                     cannot show it
 *   --report <file>   write what was found and done, as JSON
 */

import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptsDir = path.dirname(fileURLToPath(import.meta.url));

/** Whether any segment of a relative path starts with a dot. */
function isHidden(relative) {
  return relative.split('/').some((segment) => segment.startsWith('.'));
}

/**
 * Every entry of root whose path holds a segment that starts with a dot, split
 * into the directories (which a restore has to create) and the files (which it
 * has to copy), each with the installed path the app expects.
 */
function hiddenEntries(source, prefix) {
  const dirs = [];
  const files = [];
  const installed = (relative) => (prefix === "" ? relative : prefix + "/" + relative);
  const walk = (dir, relative) => {
    for (const name of fs.readdirSync(dir).sort()) {
      const absolute = path.join(dir, name);
      const child = relative === "" ? name : relative + "/" + name;
      const stat = fs.lstatSync(absolute);
      if (stat.isSymbolicLink()) {
        if (isHidden(child)) {
          throw new Error('the payload holds a link where a file is expected: ' + child + ' (a link cannot be restored into an installed app)');
        }
        continue;
      }
      if (stat.isDirectory()) {
        if (isHidden(child)) dirs.push({ relative: child, installed: installed(child) });
        walk(absolute, child);
        continue;
      }
      if (isHidden(child)) {
        files.push({ relative: child, installed: installed(child), source: absolute, bytes: stat.size });
      }
    }
  };
  walk(source, "");
  return { dirs, files };
}

/** The NSIS string of a path: quotes around it, and $ doubled, which NSIS reads. */
function nsis(pathText) {
  if (/[\r\n"]/.test(pathText)) throw new Error("a path with a quote or a line break cannot go into an NSIS string: " + pathText);
  return '"' + pathText.split('$').join('$$') + '"';
}

/** The installed path as one NSIS needs it: $INSTDIR followed by Windows separators. */
function installedPath(entry) {
  return '"$INSTDIR\\' + entry.installed.split('/').join('\\') + '"';
}

/**
 * Write the macro the installer includes. Directories first, so a file inside
 * one always lands after its directory exists; files grouped by the directory
 * they go into, so each SetOutPath is written once.
 */
function writeMacro(file, entries, source) {
  const out = [];
  out.push("; Generated by desktop/scripts/stage-mygo-dotfiles.mjs from");
  out.push("; " + source + ". Do not edit: desktop/mygo/installer/windows.nsh");
  out.push("; includes it and runs the macro below, because mygo leaves every name that");
  out.push("; starts with a dot out of the resources it copies (cmd/mygo/resources.go:643).");
  out.push("!macro RestoreDotfiles");
  if (entries.dirs.length + entries.files.length === 0) {
    out.push("  ; The staged payload holds no such entry: nothing to restore.");
  } else {
    out.push("  DetailPrint \"Restoring " + entries.files.length + " files mygo leaves out of the app resources...\"");
    for (const dir of entries.dirs) out.push("  CreateDirectory " + installedPath(dir));
    let current = "";
    for (const file of entries.files) {
      const dir = file.installed.slice(0, file.installed.lastIndexOf('/'));
      if (dir !== current) {
        out.push('  SetOutPath "$INSTDIR\\' + dir.split('/').join('\\') + '"');
        current = dir;
      }
      out.push("  File " + nsis(file.source));
    }
    out.push('  SetOutPath "$INSTDIR"');
  }
  out.push("!macroend");
  out.push("");
  fs.mkdirSync(path.dirname(file), { recursive: true });
  // UTF-8 with a byte order mark, the way makensis reads a script of this project:
  // mygo writes its own installer script with one, and a path with a non-ASCII
  // character would otherwise be read in the build machine code page.
  fs.writeFileSync(file, Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from(out.join("\n"))]));
  return out;
}

/** The SHA-256 of a file, in lower case hex. */
function digest(file) {
  return createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

/**
 * Copy the entries into appDir, or with checkOnly, verify what is there: every
 * file the same bytes as its source, every directory present. Returns what
 * differed, and whether a difference is a failure (it always is).
 */
function applyTo(appDir, entries, options) {
  const copied = [];
  const missing = [];
  const differing = [];
  const dirs = options.filesOnly ? [] : entries.dirs;
  for (const dir of dirs) {
    const target = path.join(appDir, ...dir.installed.split("/"));
    if (!fs.existsSync(target)) {
      if (options.checkOnly) missing.push(dir.installed + "/");
      else {
        fs.mkdirSync(target, { recursive: true });
        copied.push(dir.installed + "/");
      }
    }
  }
  for (const file of entries.files) {
    const target = path.join(appDir, ...file.installed.split("/"));
    if (!fs.existsSync(target)) {
      if (options.checkOnly) missing.push(file.installed);
      else {
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.copyFileSync(file.source, target);
        copied.push(file.installed);
      }
      continue;
    }
    if (digest(target) !== digest(file.source)) differing.push(file.installed);
  }
  return { copied, missing, differing };
}

/** Render a byte count the way du -sh does. */
function human(bytes) {
  const units = ['B', 'K', 'M', 'G', 'T'];
  let value = bytes;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  return (unit === 0 ? String(value) : value.toFixed(value < 10 ? 1 : 0)) + units[unit];
}

function parseArgs(argv) {
  const options = { source: undefined, prefix: "", macro: undefined, app: undefined, checkOnly: false, filesOnly: false, report: undefined };
  for (let i = 0; i < argv.length; i += 1) {
    const flag = argv[i];
    if (flag === "--check") {
      options.checkOnly = true;
      continue;
    }
    if (flag === "--files-only") {
      options.filesOnly = true;
      continue;
    }
    const value = argv[i + 1];
    if (value === undefined) throw new Error(flag + " needs a value");
    if (flag === "--source") options.source = path.resolve(value);
    else if (flag === "--prefix") options.prefix = value.replace(/^\/+|\/+$/g, "");
    else if (flag === "--macro") options.macro = path.resolve(value);
    else if (flag === "--app") options.app = path.resolve(value);
    else if (flag === "--report") options.report = path.resolve(value);
    else throw new Error("unknown flag " + flag);
    i += 1;
  }
  if (options.source === undefined) throw new Error("--source is required (the staged payload, see the header)");
  if (options.checkOnly && options.app === undefined) throw new Error("--check needs --app to check");
  if (options.app !== undefined && !fs.existsSync(options.app)) throw new Error("no app directory at " + options.app);
  return options;
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  if (!fs.existsSync(options.source)) throw new Error("no staged payload at " + options.source);
  const entries = hiddenEntries(options.source, options.prefix);
  const bytes = entries.files.reduce((sum, file) => sum + file.bytes, 0);
  const report = {
    source: options.source,
    prefix: options.prefix,
    files: entries.files.length,
    dirs: entries.dirs.length,
    bytes,
    macro: null,
    app: null,
  };
  console.log("[stage-mygo-dotfiles] " + entries.files.length + " files and " + entries.dirs.length
    + " directories mygo leaves out, " + human(bytes) + ", in " + options.source);

  if (options.macro !== undefined) {
    const written = writeMacro(options.macro, entries, options.source);
    // The macro is the only thing that puts these files into the installer, so a
    // macro that lost them would ship an app the host cannot start: check what was
    // written rather than what was meant to be.
    const text = fs.readFileSync(options.macro, "utf8");
    const commands = text.split("\n").filter((line) => line.startsWith("  File ")).length;
    if (!text.includes("!macro RestoreDotfiles") || !text.includes("!macroend")) {
      throw new Error(options.macro + " is not a RestoreDotfiles macro");
    }
    if (commands !== entries.files.length) {
      throw new Error(options.macro + " holds " + commands + " File commands for " + entries.files.length + " files the payload needs there");
    }
    report.macro = { path: options.macro, lines: written.length, commands };
    console.log("[stage-mygo-dotfiles] the installer macro: " + options.macro + " (" + commands + " File commands)");
  }

  if (options.app !== undefined) {
    const result = applyTo(options.app, entries, options);
    report.app = { path: options.app, copied: result.copied.length, missing: result.missing, differing: result.differing };
    const checkedDirs = options.filesOnly ? 0 : entries.dirs.length;
    if (options.checkOnly) {
      console.log("[stage-mygo-dotfiles] checked " + options.app + ": " + entries.files.length + " files, "
        + checkedDirs + " directories, " + result.missing.length + " missing, " + result.differing.length + " different");
    } else {
      console.log("[stage-mygo-dotfiles] copied " + result.copied.length + " entries into " + options.app
        + ", " + entries.files.length + " files and " + entries.dirs.length + " directories verified");
    }
    if (result.missing.length > 0) throw new Error(options.app + " is missing " + result.missing.length + " of them, starting with " + result.missing.slice(0, 5).join(", "));
    if (result.differing.length > 0) throw new Error(options.app + " holds " + result.differing.length + " of them with different content, starting with " + result.differing.slice(0, 5).join(", "));
  }

  if (options.report !== undefined) {
    fs.mkdirSync(path.dirname(options.report), { recursive: true });
    fs.writeFileSync(options.report, JSON.stringify(report, null, 2) + "\n");
  }
}

try {
  main();
} catch (error) {
  console.error("[stage-mygo-dotfiles] " + String(error && error.message ? error.message : error));
  process.exitCode = 1;
}
